def send_xu(fd: int, query: int, payload: list[int]) -> None:
    buf = (ctypes.c_uint8 * 7)(*payload)
    ctrl = uvc_xu_control_query(
        unit=UVC_PU_HUE_CONTROL,
        selector=2,
        query=query,
        size=7,
        data=buf,
    )
    fcntl.ioctl(fd, UVCIOC_CTRL_QUERY, ctrl)


def unpack_ds325_frame(raw_yuyv: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    blocks = raw_yuyv.reshape(-1, 16, 2)

    ir = blocks[:, :8, 0].ravel()
    flag1 = blocks[:, :8, 1].ravel()
    dep = blocks[:, 8:, 0].ravel()
    flag2 = blocks[:, 8:, 1].ravel()

    d = np.full(ir.shape, 0x0D00, dtype=np.uint16)
    dep16 = dep.astype(np.uint16)
    f1_16 = flag1.astype(np.uint16)

    m_out_long = (flag1 == 0x00) & (flag2 == 0x00)
    d[m_out_long] = 0x0F00 | dep16[m_out_long]

    m_long = (flag1 == 0xFF) & (flag2 == 0x00)
    d[m_long] = np.where(dep < 0xF0, 0x0700 | dep16, 0x07FF)[m_long]

    m_mid = (flag1 == 0xFF) & (flag2 == 0xFF)
    mid_hi = np.where(
        dep > 0xC0,
        0x0600,
        np.where(
            dep > 0x80,
            0x0500,
            np.where(dep > 0x40, 0x0400, 0x0300),
        ),
    ).astype(np.uint16)
    d[m_mid] = (mid_hi | dep16)[m_mid]

    m_out_range = (flag1 == 0x00) & (flag2 == 0xFF) & (dep >= 0xF0)
    d[m_out_range] = 0x0E00 | dep16[m_out_range]

    assigned = m_out_long | m_long | m_mid | m_out_range
    m_short = (~assigned) & (flag1 < 0x08)
    f1_adj = np.where(f1_16 <= 4, f1_16, f1_16 - 4)
    hi_short = np.where(f1_16 <= 4, 0x0200, 0x0100).astype(np.uint16)
    scaled_dep = (
        (255 - (255 * (dep16 + 255 * f1_adj) // 0x3FF))
        .astype(np.uint8)
        .astype(np.uint16)
    )
    d[m_short] = (hi_short | scaled_dep)[m_short]

    m_out_short = (~assigned) & (flag1 >= 0x08)
    d[m_out_short] = dep16[m_out_short]

    return d.reshape(240, 320), ir.reshape(240, 320)


def main() -> None:
    cap_depth = cv2.VideoCapture(DEPTH_DEV, cv2.CAP_V4L2)
    cap_depth.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"YUYV"))
    cap_depth.set(cv2.CAP_PROP_FRAME_WIDTH, 640)
    cap_depth.set(cv2.CAP_PROP_FRAME_HEIGHT, 240)
    cap_depth.set(cv2.CAP_PROP_FPS, 60)
    cap_depth.set(cv2.CAP_PROP_CONVERT_RGB, 0)

    cap_rgb = cv2.VideoCapture(RGB_DEV, cv2.CAP_V4L2) if RGB_DEV else None
    if cap_rgb:
        cap_rgb.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*"MJPG"))
        cap_rgb.set(cv2.CAP_PROP_FRAME_WIDTH, 1280)
        cap_rgb.set(cv2.CAP_PROP_FRAME_HEIGHT, 720)
        cap_rgb.set(cv2.CAP_PROP_FPS, 30)

    # Trigger VIDIOC_STREAMON on /dev/video4 before sending XU init packets
    cap_depth.read()
    ctrl_fd = os.open(DEPTH_DEV, os.O_RDWR | os.O_NONBLOCK)
    cmd_idx = 0

    try:
        while True:
            if cmd_idx < len(INIT_COMMANDS):
                query, payload = INIT_COMMANDS[cmd_idx]
                send_xu(ctrl_fd, query, payload)
                cmd_idx += 1

            ret, raw = cap_depth.read()
            if not ret:
                continue

            depth_u16, ir_u8 = unpack_ds325_frame(raw)

            valid_depth = np.where(depth_u16 < 0x0800, depth_u16, 0)
            depth_vis = cv2.normalize(
                valid_depth, None, 0, 255, cv2.NORM_MINMAX, dtype=cv2.CV_8U
            )
            depth_color = cv2.applyColorMap(depth_vis, cv2.COLORMAP_JET)

            cv2.imshow("DS325 Depth", depth_color)
            cv2.imshow("DS325 IR", ir_u8)

            if cap_rgb:
                ret_rgb, rgb = cap_rgb.read()
                if ret_rgb:
                    cv2.imshow("DS325 RGB", rgb)

            if cv2.waitKey(1) & 0xFF == 27:
                break
    finally:
        for query, payload in END_COMMANDS:
            try:
                send_xu(ctrl_fd, query, payload)
            except OSError:
                pass
        os.close(ctrl_fd)
        cap_depth.release()
        if cap_rgb:
            cap_rgb.release()
        cv2.destroyAllWindows()


if __name__ == "__main__":
    main()
