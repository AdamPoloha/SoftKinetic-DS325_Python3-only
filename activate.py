def send_xu(fd: int, query: int, payload: list[int]) -> None:
    buf = (ctypes.c_uint8 * 7)(*payload)
    ctrl = uvc_xu_control_query(
        unit=UVC_PU_HUE_CONTROL,
        selector=2,
        query=query,
        size=7,
        data=buf,
    )
    fcntl.ioctl(fd, UVCIOC_CTRL_QUERY, ctrl)


def main() -> None:
    # Start VLC first on v4l2:///dev/video4 (so VIDIOC_STREAMON is active), then run this script
    fd = os.open(DEPTH_DEV, os.O_RDWR | os.O_NONBLOCK)
    try:
        for query, payload in INIT_COMMANDS:
            send_xu(fd, query, payload)
            time.sleep(0.033)
        print("DS325 emitter enabled.")
    finally:
        os.close(fd)


if __name__ == "__main__":
    main()
